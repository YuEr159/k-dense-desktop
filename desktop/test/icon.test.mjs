/**
 * The tray icon has to be usable before it is ever looked at.
 *
 * A macOS menu-bar icon that is a solid block, or a blank square, looks like a
 * broken app rather than a stylistic choice — and the failure is silent, since
 * nothing throws. The brand source is a fully opaque greyscale mark on white,
 * so deriving the mask from alpha (the obvious move) yields a black square.
 * This checks the property that made that bug visible: the mask has to be
 * mostly clear with real ink in it.
 */
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { test } from "node:test";

const resources = path.resolve(import.meta.dirname, "..", "resources");
const repoRoot = path.resolve(import.meta.dirname, "..", "..");

function sharpFromWeb() {
  // `sharp` is not a dependency of the shell — it comes from the web build's
  // tree, which is where the icon script borrows it from. A job that installs
  // only the shell (the Windows CI one) has neither the module nor a reason to
  // download it, so the caller skips instead of failing.
  try {
    return createRequire(path.join(repoRoot, "web", "package.json"))("sharp");
  } catch {
    return null;
  }
}

test("the macOS template icon is a mark, not a block", async () => {
  const sharp = sharpFromWeb();
  if (!sharp) return;
  const file = path.join(resources, "iconTemplate.png");
  if (!fs.existsSync(file)) {
    // Generated by `make-icon.mjs`, which runs as part of every build. A
    // checkout that has not built yet is not a test failure.
    return;
  }
  const stats = await sharp(file).stats();
  const alpha = stats.channels[3];

  assert.equal(alpha.max, 255, "the mark itself must be fully opaque");
  assert.ok(alpha.min < 32, `expected transparent corners, got min ${alpha.min}`);
  // A solid block sits near 255; a mostly-empty field near 0. Ink on a
  // transparent field lands in between, and the exact value depends on how
  // much of the 32px box the mark fills.
  assert.ok(
    alpha.mean > 10 && alpha.mean < 220,
    `alpha mean ${alpha.mean.toFixed(1)} suggests a blank or solid icon`,
  );

  const { width, height } = await sharp(file).metadata();
  assert.deepEqual([width, height], [32, 32], "author at 32px for a 16pt slot");
});

test("the @2x variant is exactly twice the base size", async () => {
  const sharp = sharpFromWeb();
  if (!sharp) return;
  const base = path.join(resources, "iconTemplate.png");
  const retina = path.join(resources, "iconTemplate@2x.png");
  if (!fs.existsSync(base) || !fs.existsSync(retina)) return;
  const [a, b] = await Promise.all([sharp(base).metadata(), sharp(retina).metadata()]);
  assert.equal(b.width, a.width * 2);
  assert.equal(b.height, a.height * 2);
});
